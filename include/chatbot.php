<script>
    const aiReplyMap = <?= json_encode($aiReplies, JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE) ?: '{}' ?>;
    const aiFallbackReply = <?= json_encode($aiFallback, JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE) ?: '""' ?>;
    const aiSortedKeywords = Object.keys(aiReplyMap).sort((a, b) => b.length - a.length);

    (function () {
        const panel       = document.getElementById('aiChatPanel');
        const fab         = document.getElementById('aiChatFab');
        const closeBtn    = document.getElementById('aiChatClose');
        const messagesEl  = document.getElementById('aiChatMessages');
        const inputEl     = document.getElementById('aiChatInput');
        const sendBtn     = document.getElementById('aiChatSend');
        const suggestions = document.getElementById('aiChatSuggestions');

        if (!panel || !fab) {
            console.warn('[chatbot] panel or fab not found');
            return;
        }

        function openPanel() {
            panel.classList.add('open');
            fab.classList.add('hidden');
            if (inputEl) inputEl.focus();
        }
        function closePanel() {
            panel.classList.remove('open');
            fab.classList.remove('hidden');
        }

        fab.addEventListener('click', function (e) {
            e.stopPropagation();
            openPanel();
        });

        closeBtn.addEventListener('click', function (e) {
            e.stopPropagation();
            closePanel();
        });

        window.toggleAiChat = function () {
            panel.classList.contains('open') ? closePanel() : openPanel();
        };
        window.closeAiChat = closePanel;

        function addMessage(text, who) {
            const div = document.createElement('div');
            div.className = 'ai-msg ' + who;
            div.textContent = text;
            messagesEl.appendChild(div);
            messagesEl.scrollTop = messagesEl.scrollHeight;
            return div;
        }

        function showTyping() {
            const div = document.createElement('div');
            div.className = 'ai-msg bot typing';
            div.innerHTML = '<span></span><span></span><span></span>';
            messagesEl.appendChild(div);
            messagesEl.scrollTop = messagesEl.scrollHeight;
            return div;
        }

        function aiRespond(userText) {
            const typingEl = showTyping();
            const lower = userText.toLowerCase();
            let reply = aiFallbackReply;
            for (const keyword of aiSortedKeywords) {
                if (lower.includes(keyword)) {
                    reply = aiReplyMap[keyword];
                    break;
                }
            }
            setTimeout(function () {
                typingEl.remove();
                addMessage(reply, 'bot');
            }, 700 + Math.random() * 500);
        }

        function sendMessage(text) {
            const trimmed = (text || '').trim();
            if (!trimmed) return;
            addMessage(trimmed, 'user');
            inputEl.value = '';
            if (suggestions) suggestions.style.display = 'none';
            aiRespond(trimmed);
        }

        sendBtn.addEventListener('click', function () { sendMessage(inputEl.value); });
        inputEl.addEventListener('keydown', function (e) {
            if (e.key === 'Enter') sendMessage(inputEl.value);
        });
        suggestions.querySelectorAll('.ai-chip').forEach(function (chip) {
            chip.addEventListener('click', function () { sendMessage(chip.dataset.msg); });
        });
    })();
</script>